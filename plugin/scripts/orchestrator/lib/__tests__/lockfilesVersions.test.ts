// =============================================================
// lockfilesVersions.test.ts: the locked versions read from the lockfiles (lib/lockfiles.js parseLock and lockedVersion,
// roadmap 0å KD-3, plans/katalog-design-stack-avhengigheter-2026-11-18.md § 5.1).
//
// Locks: one small fixture per format (npm v1 and v3, pnpm v6 and v9, yarn v1 and berry, bun.lock, uv, poetry,
// Cargo, go.sum) gives the name and the version; a nested npm copy is not the top-level version; with several versions
// of one name the manifest range picks, else the highest; an unknown file, an empty one and a broken one give null
// and never throw.
// =============================================================
import { describe, expect, it } from 'vitest';

/* eslint-disable @typescript-eslint/no-require-imports, @typescript-eslint/no-explicit-any */
const L = require('../lockfiles.js') as any;
/* eslint-enable @typescript-eslint/no-require-imports, @typescript-eslint/no-explicit-any */

const v = (file: string, text: string, name: string, range?: string) => L.lockedVersion(L.parseLock(file, text), name, range);

describe('parseLock: npm', () => {
  it('package-lock v3: the top-level packages, not a nested copy', () => {
    const t = JSON.stringify({
      lockfileVersion: 3,
      packages: {
        '': { name: 'app', dependencies: { zod: '^3.23.0' } },
        'node_modules/zod': { version: '3.23.8' },
        'node_modules/@types/node': { version: '20.11.5', dev: true },
        'node_modules/a/node_modules/zod': { version: '2.0.0' },
      },
    });
    expect(v('package-lock.json', t, 'zod')).toBe('3.23.8');
    expect(v('package-lock.json', t, '@types/node')).toBe('20.11.5');
    expect(L.parseLock('package-lock.json', t).ecosystem).toBe('npm');
  });

  it('package-lock v1 and npm-shrinkwrap: the dependencies object', () => {
    const t = JSON.stringify({ lockfileVersion: 1, dependencies: { lodash: { version: '4.17.21' } } });
    expect(v('package-lock.json', t, 'lodash')).toBe('4.17.21');
    expect(v('npm-shrinkwrap.json', t, 'lodash')).toBe('4.17.21');
  });
});

describe('parseLock: pnpm', () => {
  it('v6 and v9: the root importer, with the peer suffix cut', () => {
    const t = [
      "lockfileVersion: '9.0'",
      '',
      'importers:',
      '',
      '  .:',
      '    dependencies:',
      '      zod:',
      '        specifier: ^3.23.0',
      '        version: 3.23.8',
      "      '@tanstack/react-query':",
      '        specifier: ^5.0.0',
      '        version: 5.17.9(react@18.2.0)',
      '    devDependencies:',
      '      vitest:',
      '        specifier: ^1.2.0',
      '        version: 1.2.1(@types/node@20.11.5)',
      '',
      '  packages/web:',
      '    dependencies:',
      '      zod:',
      '        specifier: ^2.0.0',
      '        version: 2.0.0',
      '',
      'packages:',
      '',
      '  zod@3.23.8:',
      "    resolution: {integrity: sha512-x}",
    ].join('\n');
    expect(v('pnpm-lock.yaml', t, 'zod')).toBe('3.23.8');
    expect(v('pnpm-lock.yaml', t, '@tanstack/react-query')).toBe('5.17.9');
    expect(v('pnpm-lock.yaml', t, 'vitest')).toBe('1.2.1');
  });

  it('v5: the top-level dependencies with a plain version', () => {
    const t = ['lockfileVersion: 5.4', '', 'specifiers:', '  dayjs: ^1.11.0', '', 'dependencies:', '  dayjs: 1.11.10', '', 'devDependencies:', '  typescript: 5.3.3'].join('\n');
    expect(v('pnpm-lock.yaml', t, 'dayjs')).toBe('1.11.10');
    expect(v('pnpm-lock.yaml', t, 'typescript')).toBe('5.3.3');
  });
});

describe('parseLock: yarn and bun', () => {
  it('yarn v1: the range in the header picks between two versions', () => {
    const t = [
      '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
      '# yarn lockfile v1',
      '',
      '"@babel/core@^7.0.0", "@babel/core@^7.1.0":',
      '  version "7.23.7"',
      '  resolved "https://registry.yarnpkg.com/x"',
      '',
      'chalk@^2.0.0:',
      '  version "2.4.2"',
      '',
      'chalk@^5.3.0:',
      '  version "5.3.0"',
    ].join('\n');
    expect(v('yarn.lock', t, '@babel/core')).toBe('7.23.7');
    expect(v('yarn.lock', t, 'chalk', '^2.0.0')).toBe('2.4.2');
    expect(v('yarn.lock', t, 'chalk')).toBe('5.3.0');
  });

  it('yarn berry: the npm: protocol in the header and version: without quotes', () => {
    const t = ['__metadata:', '  version: 6', '', '"zod@npm:^3.22.0":', '  version: 3.22.4', '  resolution: "zod@npm:3.22.4"'].join('\n');
    expect(v('yarn.lock', t, 'zod', '^3.22.0')).toBe('3.22.4');
  });

  it('bun.lock: the text lockfile with trailing commas', () => {
    const t = '{\n  "lockfileVersion": 1,\n  "packages": {\n    "zod": ["zod@3.23.8", "", {}, "sha512-x"],\n    "@types/bun": ["@types/bun@1.1.0", "", {}, "sha"],\n  },\n}\n';
    expect(v('bun.lock', t, 'zod')).toBe('3.23.8');
    expect(v('bun.lock', t, '@types/bun')).toBe('1.1.0');
  });
});

describe('parseLock: Python, Rust and Go', () => {
  it('uv.lock and poetry.lock: [[package]] tables, names compared the PyPI way', () => {
    const uv = ['version = 1', '', '[[package]]', 'name = "requests"', 'version = "2.31.0"', 'source = { registry = "https://pypi.org/simple" }', '', '[[package]]', 'name = "typing-extensions"', 'version = "4.9.0"'].join('\n');
    expect(v('uv.lock', uv, 'requests')).toBe('2.31.0');
    expect(v('uv.lock', uv, 'Typing_Extensions')).toBe('4.9.0');
    const poetry = ['[[package]]', 'name = "django"', 'version = "5.0.1"', 'description = "x"', '', '[metadata]', 'lock-version = "2.0"'].join('\n');
    expect(v('poetry.lock', poetry, 'Django')).toBe('5.0.1');
    expect(L.parseLock('poetry.lock', poetry).ecosystem).toBe('python');
  });

  it('Cargo.lock: two versions of one crate, the highest without a range', () => {
    const t = ['version = 3', '', '[[package]]', 'name = "syn"', 'version = "1.0.109"', '', '[[package]]', 'name = "syn"', 'version = "2.0.48"', '', '[[package]]', 'name = "serde"', 'version = "1.0.195"'].join('\n');
    expect(v('Cargo.lock', t, 'serde')).toBe('1.0.195');
    expect(v('Cargo.lock', t, 'syn')).toBe('2.0.48');
    expect(v('Cargo.lock', t, 'syn', '1')).toBe('1.0.109');
  });

  it('go.sum: the module versions with the /go.mod suffix cut, the highest without a range', () => {
    const t = [
      'github.com/gin-gonic/gin v1.9.0 h1:abc=',
      'github.com/gin-gonic/gin v1.9.0/go.mod h1:def=',
      'github.com/gin-gonic/gin v1.9.1 h1:ghi=',
      'github.com/gin-gonic/gin v1.9.1/go.mod h1:jkl=',
      'golang.org/x/text v0.3.7/go.mod h1:mno=',
    ].join('\n');
    expect(v('go.sum', t, 'github.com/gin-gonic/gin')).toBe('v1.9.1');
    expect(v('go.sum', t, 'github.com/gin-gonic/gin', 'v1.9.0')).toBe('v1.9.0');
    expect(v('go.sum', t, 'golang.org/x/text')).toBe('v0.3.7');
  });
});

describe('parseLock: never a throw', () => {
  it('an unknown file, an empty one and a broken one give null, and a missing name no version', () => {
    expect(L.parseLock('Gemfile.lock', 'GEM\n')).toBeNull();
    expect(L.parseLock('package-lock.json', '{ not json')).toBeNull();
    expect(L.parseLock('package-lock.json', '')).toBeNull();
    expect(L.parseLock('bun.lockb', '\u0000\u0001')).toBeNull();
    expect(L.parseLock('uv.lock', null)).toBeNull();
    expect(L.parseLock('pnpm-lock.yaml', '::: [')).not.toBeUndefined();
    expect(v('Cargo.lock', '[[package]]\nname = "serde"\n', 'serde')).toBeNull();
    expect(L.lockedVersion(null, 'zod')).toBeNull();
    expect(() => L.parseLock('yarn.lock', '"\n"\n  version')).not.toThrow();
  });

  it('a lockfile in a folder is read by its file name', () => {
    expect(v('web/package-lock.json', JSON.stringify({ packages: { 'node_modules/zod': { version: '3.0.0' } } }), 'zod')).toBe('3.0.0');
  });
});
