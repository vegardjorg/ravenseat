// =============================================================
// gitSurfaceBaseline.js: the accepted state of what in git runs code (lib/gitExecSurface.js), kept between runs.
//
// Why: comparing the surface before and after one run has two holes. A hook planted by a gate makes that run red, but a
// rerun compares against the already changed "before" and goes green; and a hook written outside any run is never seen.
// So the data folder keeps what was last accepted, and cq receive, cq merge and push-check compare against that BEFORE
// the next git command that could run it. A difference is the owner's decision, never a fix round.
//
// Most differences are not an attack: someone installed husky or lefthook, or changed a global alias. The stop text
// (driftMessage) is written for that person: what differs, that it is normal, why the queue stops, the exact next step.
// `tampered` stays for a change seen during a run of track code (watch), never for this message.
//
// The file: <dataFolder>/git-surface.json, { v: 1, hooksDir, hooks, config: { <key>: <sha256 of its values> }, accepted_at,
// by }. Config values are never stored or printed (they can hold secrets); reasons name files and keys only. hooksDir goes
// through realpath so that a Windows 8.3 path and a long path are the same folder.
//
// Who writes it: ensure (trust on first use: only when the file is missing; a file that does not parse stops instead,
// so breaking it cannot get a new silent first use), accept (`cq surface accept --by owner`) and watch's write-back.
//
// The surface is read in the MAIN checkout whatever folder is asked (mainCheckout): that is where the orchestrator's git
// commands run, and a relative core.hooksPath (husky's .husky/_) or an includeIf gitdir: names another folder per worktree.
//
// Limits: detection again, not prevention (lib/gitExecSurface.js, header). Same OS user: an agent's Bash can rewrite or
// remove this file outside a gate run (the guards deny the commands that name it, see lib/gateEvidence.js tamperReason
// and lib/writeGuard.js). What exists at the first ensure is trusted.
//
// Pure: toBaseline's rule, parseConfigOrigins, differences, hookManagerHint, driftMessage, tamperedMessage. The rest is
// I/O and never throws. Tested in __tests__/gitSurfaceBaseline.test.ts.
// =============================================================
'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const GX = require('./gitExecSurface.js');

const FILE_NAME = 'git-surface.json';
/** The start of a reason that is about the accepted baseline alone (nothing changed during the run). */
const DRIFT_PREFIX = 'git hooks or config differ from the accepted baseline';
/** How much of a changed hook is read for the hint. */
const MAX_HINT_BYTES = 1 << 16;
/** Words a hook tool leaves in the hooks it writes. Only ever a hint. */
const MANAGERS = [
  ['husky', /husky/i],
  ['lefthook', /lefthook/i],
  ['pre-commit', /generated by pre-commit/i],
  ['overcommit', /overcommit/i],
  ['simple-git-hooks', /simple-git-hooks/i],
];
/** Where the longer explanation is. */
const DOCS = 'docs/queue.md, "Git hooks and config"';

const fileOf = (folder) => (folder ? path.join(folder, FILE_NAME) : null);

/** The baseline file's text, or null when it is missing or there is no folder. */
function readText(folder) {
  try {
    return fs.readFileSync(fileOf(folder), 'utf8');
  } catch {
    return null;
  }
}

/** Writes through a temporary file and a rename, so a reader sees the old text or the new one. */
function writeText(folder, text) {
  fs.mkdirSync(folder, { recursive: true });
  const tmp = `${fileOf(folder)}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, fileOf(folder));
}

/**
 * The baseline: null when there is none, `{ unreadable: true }` when the file exists but is not a baseline of this
 * version (the caller stops; it is never replaced silently).
 */
function read(folder) {
  const text = readText(folder);
  if (text == null) return null;
  try {
    const b = JSON.parse(text);
    return b && b.v === 1 ? b : { unreadable: true };
  } catch {
    return { unreadable: true };
  }
}

/** The real path, also for a folder that does not exist yet: the nearest existing parent is resolved, the rest kept. */
function realPath(p) {
  const rest = [];
  let cur = path.resolve(p);
  for (;;) {
    try {
      return path.join(fs.realpathSync.native(cur), ...rest);
    } catch {
      const up = path.dirname(cur);
      if (up === cur) return path.resolve(p);
      rest.unshift(path.basename(cur));
      cur = up;
    }
  }
}

const sha256 = (text) => crypto.createHash('sha256').update(text).digest('hex');

/**
 * A surface in the baseline's form: the folder after realpath, the config values as one hash per key. What could not be
 * read stays null, which is what surfaceChanges reads as "can no longer be found".
 * Pure given `real` (the default touches only the folder's own path).
 */
function toBaseline(surface, { real = realPath } = {}) {
  const config = surface?.config
    ? Object.fromEntries(Object.entries(surface.config).map(([k, v]) => [k, sha256(JSON.stringify(v))]))
    : null;
  return { hooksDir: surface?.hooksDir ? real(surface.hooksDir) : null, hooks: surface?.hooks ?? null, config };
}

/** The main checkout of the repository `cwd` belongs to; `cwd` itself when git cannot say or it is a bare repo. */
function mainCheckout(cwd) {
  const text = GX.gitOut(cwd, ['worktree', 'list', '--porcelain']);
  if (text == null) return cwd;
  const [first] = text.split(/\r?\n\r?\n/);
  const lines = first.split(/\r?\n/);
  const main = lines[0]?.startsWith('worktree ') ? lines[0].slice('worktree '.length) : null;
  return main && !lines.includes('bare') && fs.existsSync(main) ? main : cwd;
}

/** The surface now, in the baseline's form, and the folder it was read in. */
function current(cwd) {
  const main = mainCheckout(cwd);
  return { main, now: toBaseline(GX.readSurface(main)) };
}

/** Trust on first use: writes the current state when there is no file. Silent; a repo git cannot read writes nothing. */
function ensure(folder, cwd) {
  try {
    if (readText(folder) != null) return;
    const { now } = current(cwd);
    if (!now.hooksDir || !now.hooks || !now.config) return;
    writeText(folder, `${JSON.stringify({ v: 1, ...now, accepted_at: new Date().toISOString(), by: 'first use' }, null, 2)}\n`);
  } catch {
    // error-ignored: no baseline means no drift stop yet; the next command tries again
  }
}

/**
 * Accepts the current state. @returns {{ ok: true, baseline: object } | { ok: false, error: string }}
 */
function accept(folder, cwd, by) {
  const { now } = current(cwd);
  if (!now.hooksDir || !now.hooks || !now.config)
    return { ok: false, error: 'git cannot read the hooks folder or the config here' };
  try {
    const baseline = { v: 1, ...now, accepted_at: new Date().toISOString(), by };
    writeText(folder, `${JSON.stringify(baseline, null, 2)}\n`);
    return { ok: true, baseline };
  } catch (e) {
    return { ok: false, error: `could not write ${fileOf(folder)}: ${e?.message ?? e}` };
  }
}

const UNREADABLE = 'the file that holds the accepted baseline cannot be read';

/** The phrases for what differs from the baseline ([] when it matches or there is none). Names only. */
function changesNow(folder, cwd) {
  const b = read(folder);
  if (!b) return [];
  if (b.unreadable) return [UNREADABLE];
  return GX.surfaceChanges(b, current(cwd).now);
}

/** The reason text for a drifted surface, or null (also null when there is no baseline). Names only. */
function driftReason(folder, cwd) {
  const list = changesNow(folder, cwd);
  return list.length ? `${DRIFT_PREFIX} (${list.join('; ')})` : null;
}

/** Is this reason about the baseline alone (no change during the run)? Pure. */
const isDriftOnly = (reason) => String(reason ?? '').startsWith(DRIFT_PREFIX);

/**
 * Started before the first command of a run of track code: `finish()` after the last one.
 * Combines (1) the comparison during the run, (2) the baseline file itself: a change is undone (the old text written
 * back, or the file removed when there was none) and named, (3) the drift check, unless `drift: false` (a track's own run:
 * an owner's new hook must not make every track red). @returns the reason text, or null. Names only.
 */
function watch(folder, cwd) {
  const before = GX.readSurface(cwd);
  const textBefore = readText(folder);
  return {
    finish({ drift = true } = {}) {
      const parts = [];
      const during = GX.surfaceChanges(before, GX.readSurface(cwd));
      if (during.length) parts.push(`git hooks or config changed during the run (${during.join('; ')})`);
      if (readText(folder) !== textBefore) {
        let back = 'the old text was written back';
        try {
          if (textBefore == null) fs.rmSync(fileOf(folder), { force: true });
          else writeText(folder, textBefore);
        } catch {
          back = 'the old text could NOT be written back';
        }
        parts.push(`the accepted baseline file changed during the run; ${back}`);
      }
      if (drift) {
        const left = changesNow(folder, cwd).filter((c) => !during.includes(c));
        if (left.length) parts.push(`${DRIFT_PREFIX} (${left.join('; ')})`);
      }
      return parts.length ? parts.join('; ') : null;
    },
  };
}

// ---- What a person reads --------------------------------------------------------------------------------------------

/**
 * Executing keys and where each is set, from `git config --null --show-scope --show-origin --list` (records of scope,
 * origin and "key\nvalue"; a key without a value has no newline). The value is dropped here. Pure.
 * @returns {Record<string, string[]>} key -> ['global: <file>', ...]
 */
function parseConfigOrigins(text) {
  const parts = String(text ?? '').split('\0');
  const out = {};
  for (let i = 0; i + 2 < parts.length; i += 3) {
    const nl = parts[i + 2].indexOf('\n');
    const key = nl < 0 ? parts[i + 2] : parts[i + 2].slice(0, nl);
    if (!GX.isExecKey(key)) continue;
    const where = `${parts[i]}: ${parts[i + 1].replace(/^file:/, '')}`;
    if (!(out[key] ??= []).includes(where)) out[key].push(where);
  }
  return out;
}

/**
 * Every difference with its kind and where to look. `where` is a full path for a hook, the origin for a config key.
 * Pure. @returns {{ kind: string, name: string, where: string }[]}
 */
function differences(before, after, origins = {}) {
  const out = [];
  if (before?.hooksDir && before.hooks && after?.hooks) {
    if (after.hooksDir !== before.hooksDir)
      out.push({ kind: 'hooks folder moved', name: `from ${before.hooksDir}`, where: after.hooksDir });
    else {
      for (const k of GX.differingKeys(before.hooks, after.hooks)) {
        const kind = !(k in before.hooks) ? 'hook added' : !(k in after.hooks) ? 'hook removed' : 'hook changed';
        out.push({ kind, name: k, where: path.join(after.hooksDir, ...k.split('/')) });
      }
    }
  }
  if (before?.config && after?.config)
    for (const k of GX.differingKeys(before.config, after.config)) {
      const gone = !(k in after.config);
      const kind = gone ? 'git config removed' : !(k in before.config) ? 'git config added' : 'git config changed';
      const seen = origins[k]?.join(', ');
      out.push({ kind, name: k, where: gone ? 'no longer set' : seen ?? 'see git config --list --show-origin' });
    }
  return out;
}

/**
 * A hint that a hook tool made this difference: the hooks folder moved to a tracked folder in the repository, or a changed
 * hook carries a tool's name. Only ever said as a hint: anyone can write the word. Pure.
 */
function hookManagerHint({ moved = false, movedToTracked = false, hookTexts = [] }) {
  for (const [name, re] of MANAGERS) if (hookTexts.some((t) => re.test(t))) return `looks like a hook manager (${name})`;
  return moved && movedToTracked ? 'looks like a hook manager' : null;
}

/** Are files tracked in the moved-to hooks folder, or its parent (husky: .husky/_ is generated, .husky is tracked)? */
function trackedFolder(main, hooksDir) {
  const rel = path.relative(realPath(main), hooksDir);
  if (!rel || rel.startsWith('..') || path.isAbsolute(rel)) return false;
  const parts = rel.split(path.sep);
  if (parts[0] === '.git') return false;
  const asked = [rel, ...(parts.length > 1 ? [path.dirname(rel)] : [])].map((p) => p.split(path.sep).join('/'));
  // The executing fsmonitor stays off for a command that runs on a surface already known to differ.
  const listed = GX.gitOut(main, ['-c', 'core.fsmonitor=false', 'ls-files', '--', ...asked]);
  return Boolean(listed && listed.trim());
}

/** The start of a changed hook, for the hint; '' when it cannot be read. */
function hookStart(file) {
  try {
    const fd = fs.openSync(file, 'r');
    try {
      const buf = Buffer.alloc(MAX_HINT_BYTES);
      return buf.toString('utf8', 0, fs.readSync(fd, buf, 0, MAX_HINT_BYTES, 0));
    } finally {
      fs.closeSync(fd);
    }
  } catch {
    return '';
  }
}

/**
 * What differs in full, for the stop message and `cq surface`: null when it matches or there is no baseline.
 * @returns {null | { reason: string, changes: string[], differences: object[], hint: string|null }}
 */
function driftDetail(folder, cwd) {
  const b = read(folder);
  const changes = changesNow(folder, cwd);
  if (!changes.length) return null;
  const reason = `${DRIFT_PREFIX} (${changes.join('; ')})`;
  if (b.unreadable) return { reason, changes, differences: [], hint: null };
  const { main, now } = current(cwd);
  const origins = parseConfigOrigins(GX.gitOut(main, ['config', '--null', '--show-scope', '--show-origin', '--list']));
  // git names the repository's own config relatively (.git/config): a full path says where to look from anywhere.
  for (const k of Object.keys(origins))
    origins[k] = origins[k].map((o) => o.replace(/^(local|worktree): (\.git[\\/].*)$/, (_, scope, file) => `${scope}: ${path.resolve(main, file)}`));
  const list = differences(b, now, origins);
  const moved = list.some((d) => d.kind === 'hooks folder moved');
  const hint = hookManagerHint({
    moved,
    movedToTracked: moved && now.hooksDir ? trackedFolder(main, now.hooksDir) : false,
    // Also after a move: the hooks in the new folder say which tool it is.
    hookTexts: moved
      ? Object.keys(now.hooks ?? {}).slice(0, 20).map((k) => hookStart(path.join(now.hooksDir, k)))
      : list.filter((d) => d.kind === 'hook added' || d.kind === 'hook changed').map((d) => hookStart(d.where)),
  });
  return { reason, changes, differences: list, hint };
}

/** The owner's two ways out, in the words of the stop message. Pure. */
function nextSteps({ cq, again }) {
  return [
    'Next step:',
    `  ${cq} surface                     shows each difference and where it lives`,
    `  ${cq} surface accept --by owner   if you made this change: accepts it, one command, nothing else to do`,
    `  Otherwise remove it${again ? `, then run ${again} again` : ', then run this again'}.`,
  ];
}

/**
 * The stop message for a drifted surface. For someone who did nothing wrong: what differs (names only), that this is
 * normal, why the stop, the next step. No queue words: it must read the same in lite mode. Pure.
 * @param {{ changes: string[], hint?: string|null, cq: string, again?: string|null, afterRun?: boolean }} o
 */
function driftMessage({ changes, hint = null, cq, again = null, afterRun = false }) {
  const what = "this repository's git hooks or git settings are not the ones accepted earlier.";
  return [
    afterRun ? `This check counts as failed: ${what}` : `Stopped before running anything: ${what}`,
    `  What differs: ${changes.join('; ')}`,
    ...(hint ? [`  Hint: this ${hint}. It is only a hint; nothing is accepted because of it.`] : []),
    'This is normal after installing a hook tool (husky, lefthook) or changing your git config.',
    'Why it stops: hooks and these settings run code at the next git command, with your credentials, and automated work',
    'in this repository could have put them there. Only you can tell which it is.',
    ...nextSteps({ cq, again }),
    `${afterRun ? '' : 'Nothing changed. '}More in ${DOCS}.`,
  ].join('\n');
}

/**
 * The stop when a run of the code under test changed something. This one does say tampered: it was seen during the run.
 * Pure.
 * @param {{ what: string, reason: string, cq: string, again?: string|null }} o
 */
function tamperedMessage({ what, reason, cq, again = null }) {
  const storeOnly = !/git hooks or config|baseline/.test(reason);
  return [
    `STOP, the owner decides: ${what} changed something outside the code it was checking.`,
    `  TAMPERED: ${reason}.`,
    'No fix round is started: code that changes these should not be sent back to an agent to be fixed.',
    ...(storeOnly
      ? [`What it changed was dropped. Read the code that ran; ${again ?? 'the same command'} runs it again.`]
      : [`${GX.INSPECT}.`, ...nextSteps({ cq, again })]),
    `Nothing changed in the queue. More in ${DOCS}.`,
  ].join('\n');
}

